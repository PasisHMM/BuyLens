def _noted(fit: FitCheck) -> FitCheck:
    """A MATCH against this chart always says the chart itself is unverified."""
    if fit.outcome is not FitOutcome.MATCH:
        return fit
    return fit.model_copy(update={"reasons": [*fit.reasons, _UNVERIFIED]})


def _variant(fit: FitCheck) -> dict[str, Any]:
    noted = _noted(fit)
    return {"group": result_group(noted.outcome), "fit": noted.model_dump(mode="json")}


def demo_quick_fit(product: DemoProduct, sizes: Mapping[FitCategory, QuickSize]) -> FitCheck:
    return quick_fit(product.product_type, DEMO_CHART, product.sold_sizes, sizes)


def demo_personal_fit(product: DemoProduct, cm: Mapping[Dimension, float]) -> FitCheck:
    measured = {d: Measurement(v) for d, v in cm.items()}
    return personal_fit(product.product_type, DEMO_CHART, product.sold_sizes, measured)


def _quick_variants(product: DemoProduct) -> dict[str, dict[str, Any]]:
    category = (
        fit_category_for(product.product_type) or FitCategory.TOPS
    )  # without rules, any size is the same
    variants = {s.value: _variant(demo_quick_fit(product, {category: s})) for s in QuickSize}
    variants["none"] = _variant(demo_quick_fit(product, {}))
    return variants


def _own_measurements_variant(product: DemoProduct) -> dict[str, Any]:
    """For someone's own numbers the browser can only state what the chart lacks for anyone."""
    fit = demo_personal_fit(product, {})
    known_to_everyone = [r for r in fit.reasons if not r.startswith("Add your")]
    return _variant(fit.model_copy(update={"reasons": known_to_everyone}))


def _option(product: DemoProduct) -> dict[str, Any]:
    price = PriceCheck(
        currency="EUR",
        listing_cents=product.price_cents,
        shipping_cents=None,
        total_cents=product.price_cents,
        total_is_estimate=True,
    )
    risk = SellerRisk(
        seller_name=SHOP["name"],
        is_official=False,
        trust_rating=None,
        level=None,
        review_rating=None,
        review_count=None,
        return_policy=ReturnPolicy(),
        review_highlights=[],
    )
    return {
        "rank": 1,
        "listing_id": str(uuid5(NAMESPACE_URL, product.input_url)),
        "seller": _SELLER,
        "url": product.product_url or "",
        "total_cents": product.price_cents,
        "summary": "Demo shop",
        "price_check": price.model_dump(mode="json"),
        "seller_risk": risk.model_dump(mode="json"),
    }


def _product_out(product: DemoProduct) -> dict[str, Any]:
    return {
        "id": product.id,
        "name": product.name,
        "product_type": product.product_type.value,
        "product_type_label": PRODUCT_TYPES[product.product_type].label,
        "fit_category": PRODUCT_TYPES[product.product_type].fit_category,
        "sold_sizes": list(product.sold_sizes),
        "input_url": product.input_url,
        "option": _option(product),
        "quick_fit": _quick_variants(product),
        "personal_fit": _own_measurements_variant(product),
        "sample_fit": {
            s.id: _variant(demo_personal_fit(product, s.measurements_cm)) for s in PERSONAL_SAMPLES
        },
    }


def _row_out(row: DemoRow) -> dict[str, Any]:
    def cm(published: Range) -> dict[str, float]:
        return {"min_cm": float(published[0]), "max_cm": float(published[1])}

    return {
        "label": row.label,
        "eu": row.eu,
        "uk": row.uk,
        "chest": cm(row.chest),
        "waist": cm(row.waist),
        "hips": cm(row.hips),
    }


def _sample_out(sample: PersonalSample) -> dict[str, Any]:
    return {
        "id": sample.id,
        "label": sample.label,
        "measurements": [
            {"dimension": d.value, "value_cm": float(v), "basis": Basis.BODY.value}
            for d, v in sample.measurements_cm.items()
        ],
    }


def prototype_fixture() -> dict[str, Any]:
    """Everything the browser prototype needs, decided here so that TypeScript holds no fit rules."""
    return {
        "shop": SHOP,
        "chart": {**CHART_INFO, "rows": [_row_out(r) for r in DEMO_ROWS]},
        "personal_samples": [_sample_out(s) for s in PERSONAL_SAMPLES],
        "products": [_product_out(p) for p in DEMO_PRODUCTS],
    }
