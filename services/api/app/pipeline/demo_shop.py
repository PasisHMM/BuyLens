"""Merchandizable: the fictional demonstration shop of the mock-first prototype (docs/redesign-plan.md §11).

Its chart is sample data with its own size labels, so it stays apart from the global catalog: XXS, XXL,
3XL and 4XL are not Quick Fit sizes and are never mapped onto them. The fit rules and tolerances are the
signed-off ones from measurements.py. The browser prototype has no Python host, so it reads
prototype_fixture(), generated by scripts/export_catalog.py.
"""

from collections.abc import Mapping
from dataclasses import dataclass
from typing import Any

