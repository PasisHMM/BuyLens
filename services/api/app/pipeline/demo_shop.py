from app.pipeline.measurements import CategoryRule, is_plausible, rule_for
from app.pipeline.models import Basis, Dimension, FitCategory, FitOutcome, QuickSize

_D = Dimension
_NO_RULES = "No fit rules for this product type yet."
_WAIST_LENGTH = "This product uses waist/length sizes, which the demo chart doesn't describe."
_UNVERIFIED = "The demo chart is sample data, not independently verified."


@dataclass(frozen=True)
class ChartRange:
    min_cm: float
    max_cm: float

    def __post_init__(self) -> None:
        if self.min_cm >= self.max_cm:
            raise ValueError("min_cm must be below max_cm.")

    def covers(self, cm: float, tolerance_cm: float = 0.0) -> bool:
        return self.min_cm - tolerance_cm <= cm <= self.max_cm + tolerance_cm


@dataclass(frozen=True)
class ChartRow:
    label: str
    eu: str  # kept as printed: labels are not body measurements
    uk: str
    ranges: Mapping[Dimension, ChartRange]

    def __post_init__(self) -> None:
        for dimension, cm in self.ranges.items():
            if not (is_plausible(dimension, cm.min_cm) and is_plausible(dimension, cm.max_cm)):
                raise ValueError(f"{dimension} range is outside the plausible adult range.")


@dataclass(frozen=True)
class DemoChart:
    title: str
    disclaimer: str
    basis: Basis
    sizing_mode: str
    unavailable_modes: tuple[str, ...]  # shown by the source without any measurements, so left empty
    rows: tuple[ChartRow, ...]

    def row(self, label: str) -> ChartRow | None:
        return next((r for r in self.rows if r.label == label), None)

    def lists(self, dimension: Dimension) -> bool:
        return all(dimension in r.ranges for r in self.rows)


def _row(label: str, eu: str, uk: str, chest: tuple[float, float], waist: tuple[float, float],
         hips: tuple[float, float]) -> ChartRow:  # fmt: skip
    return ChartRow(
        label,
        eu,
        uk,
        {_D.CHEST: ChartRange(*chest), _D.WAIST: ChartRange(*waist), _D.HIPS: ChartRange(*hips)},
    )


