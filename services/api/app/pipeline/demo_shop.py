Range = tuple[float, float]


@dataclass(frozen=True)
class DemoRow:
    label: str
    eu: str  # kept as printed: labels are not body measurements
    uk: str
    chest: Range
    waist: Range
    hips: Range

    def chart_size(self) -> ChartSize:
        ranges = {_D.CHEST: self.chest, _D.WAIST: self.waist, _D.HIPS: self.hips}
        for dimension, (low, high) in ranges.items():
            if not (is_plausible(dimension, low) and is_plausible(dimension, high)):
                raise ValueError(f"{dimension} range is outside the plausible adult range.")
            if low >= high:
                raise ValueError("min_cm must be below max_cm.")
        return ChartSize(self.label, {d: Interval(a, b, Basis.BODY) for d, (a, b) in ranges.items()})


