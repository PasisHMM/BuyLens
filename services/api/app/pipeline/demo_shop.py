@dataclass(frozen=True)
class DemoFit:
    outcome: FitOutcome
    size_label: str | None
    reasons: tuple[str, ...]


def _uncertain(*reasons: str, size_label: str | None = None) -> DemoFit:
    return DemoFit(FitOutcome.UNCERTAIN, size_label, reasons)


def quick_fit(product: DemoProduct, sizes: Mapping[FitCategory, QuickSize]) -> DemoFit:
    """Approximate by design, so it can only be MATCH or UNCERTAIN."""
    if product.category is None:
        return _uncertain(_NO_RULES)
    size = sizes.get(product.category)
    if size is None:
        return _uncertain(f"Add your {product.category.value.capitalize()} size.")
    if size.value not in product.sold_sizes:
        return _uncertain(f"This product isn't listed in size {size.value}.")
    if DEMO_CHART.row(size.value) is None:
        return _uncertain(f"The demo chart doesn't cover size {size.value}.")
    return DemoFit(
        FitOutcome.MATCH,
        size.value,
        (f"Approximate fit based on size {size.value}. The product is listed in this size.", _UNVERIFIED),
    )


def _sold_rows(product: DemoProduct) -> list[ChartRow]:
    return [r for s in product.sold_sizes if (r := DEMO_CHART.row(s)) is not None]


def _unlisted(needed: frozenset[Dimension]) -> list[str]:
    return [
        f"The demo chart doesn't list {d.value}."
        for d in Dimension
        if d in needed and not DEMO_CHART.lists(d)
    ]


def _gaps(needed: frozenset[Dimension], mine: Mapping[Dimension, float]) -> list[str]:
    """What the comparison lacks. Nothing here is ever filled in with a guess."""
    missing = [
        f"Add your {d.value}." for d in Dimension if d in needed and DEMO_CHART.lists(d) and d not in mine
    ]
    return _unlisted(needed) + missing


def _comparable(group: frozenset[Dimension], mine: Mapping[Dimension, float]) -> list[Dimension]:
    return [d for d in Dimension if d in group and d in mine and DEMO_CHART.lists(d)]


def _within(
    rows: list[ChartRow], dimensions: list[Dimension], mine: Mapping[Dimension, float], tolerance: float
) -> list[ChartRow]:
    return [r for r in rows if all(r.ranges[d].covers(mine[d], tolerance) for d in dimensions)]


def _compare(
    rows: list[ChartRow], rule: CategoryRule, mine: Mapping[Dimension, float], gaps: list[str]
) -> DemoFit:
    tolerance = rule.tolerance_cm(DEMO_CHART.basis)
    critical = _comparable(rule.critical, mine)
    fitting = _within(rows, critical, mine, tolerance)
    if not fitting:
        reason = f"No listed size is within tolerance for {', '.join(critical)}."
        return DemoFit(FitOutcome.MISMATCH, None, (reason,))
    secondary = _comparable(rule.secondary, mine)
    fully = _within(fitting, secondary, mine, tolerance)
    if not fully:
        names = ", ".join(secondary).capitalize()
        return _uncertain(f"{names} is outside this size's range.", *gaps, size_label=fitting[0].label)
    label = fully[0].label
    if gaps:
        return _uncertain(*gaps, _UNVERIFIED, size_label=label)
    return DemoFit(
        FitOutcome.MATCH, label, (f"Your measurements are within tolerance for size {label}.", _UNVERIFIED)
    )


def personal_fit(product: DemoProduct, measurements: Mapping[Dimension, Measurement]) -> DemoFit:
    """Compare body measurements with the body chart using the category's signed-off rules."""
    if product.category is None:
        return _uncertain(_NO_RULES)
    rows = _sold_rows(product)
    if not rows:
        return _uncertain(_WAIST_LENGTH)
    rule = rule_for(product.category)
    # A garment measurement says nothing about a body chart, so it counts as missing.
    mine = {d: m.value_cm for d, m in measurements.items() if m.basis is DEMO_CHART.basis}
    gaps = _gaps(rule.critical | rule.secondary, mine)
    if not _comparable(rule.critical, mine):
        return _uncertain("The demo chart is a body chart, so it needs body measurements.", *gaps)
    return _compare(rows, rule, mine, gaps)


def _browser_personal_fit(product: DemoProduct) -> DemoFit:
    """The browser can't run personal_fit, so it may only state what the chart lacks for anyone."""
    if product.category is None:
        return _uncertain(_NO_RULES)
    if not _sold_rows(product):
        return _uncertain(_WAIST_LENGTH)
    rule = rule_for(product.category)
    return _uncertain(*_unlisted(rule.critical | rule.secondary))


def _fit_out(fit: DemoFit) -> dict[str, Any]:
    return {"outcome": fit.outcome.value, "size_label": fit.size_label, "reasons": list(fit.reasons)}


def _quick_outcomes(product: DemoProduct) -> dict[str, dict[str, Any]]:
    category = product.category or FitCategory.TOPS  # with no rules every size gives the same answer
    outcomes = {s.value: _fit_out(quick_fit(product, {category: s})) for s in QuickSize}
    outcomes["none"] = _fit_out(quick_fit(product, {}))
    return outcomes


def _product_out(product: DemoProduct) -> dict[str, Any]:
    return {
        "id": product.id,
        "name": product.name,
        "product_type": product.product_type,
        "category": product.category.value if product.category else None,
        "price_cents": product.price_cents,
        "currency": "EUR",
        "sold_sizes": list(product.sold_sizes),
        "input_url": product.input_url,
        "product_url": product.product_url,
        "quick_fit": _quick_outcomes(product),
        "personal_fit": _fit_out(_browser_personal_fit(product)),
    }


def _row_out(row: ChartRow) -> dict[str, Any]:
    ranges = {d.value: {"min_cm": float(c.min_cm), "max_cm": float(c.max_cm)} for d, c in row.ranges.items()}
    return {"label": row.label, "eu": row.eu, "uk": row.uk, **ranges}


def prototype_fixture() -> dict[str, Any]:
    """Everything the browser prototype needs, decided here so that TypeScript holds no fit rules."""
    return {
        "shop": {"id": "merchandizable", "name": "Merchandizable"},
        "chart": {
            "title": DEMO_CHART.title,
            "disclaimer": DEMO_CHART.disclaimer,
            "basis": DEMO_CHART.basis.value,
            "sizing_mode": DEMO_CHART.sizing_mode,
            "unavailable_modes": list(DEMO_CHART.unavailable_modes),
            "rows": [_row_out(r) for r in DEMO_CHART.rows],
        },
        "products": [_product_out(p) for p in DEMO_PRODUCTS],
    }
