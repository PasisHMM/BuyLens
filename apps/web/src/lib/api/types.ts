/** App-facing API types. Response shapes come from the backend's OpenAPI contract (schema.d.ts). */
import type { components } from "./schema";

type Schemas = components["schemas"];

export type Unit = "in" | "cm";
export type Brand = Schemas["Brand"];
export type Profile = Schemas["ProfileOut"];
export type ProfileIn = Schemas["ProfileIn"];
export type CheckResult = Schemas["CheckResult"];
export type CheckSummary = Schemas["CheckSummary"];
export type OptionOut = Schemas["OptionOut"];
export type PriceCheck = Schemas["PriceCheck"];
export type FitCheck = Schemas["FitCheck"];
export type FitRow = Schemas["FitRow"];
export type FitOutcome = Schemas["FitOutcome"];
export type SellerRisk = Schemas["SellerRisk"];

export type Catalog = Schemas["Catalog"];
export type FitMode = Schemas["FitMode"];
export type QuickSize = Schemas["QuickSize"];
export type FitCategory = Schemas["FitCategory"];
export type ProfileMeasurement = Schemas["MeasurementOut"];
export type MeasurementIn = Schemas["MeasurementIn"];
export type Basis = Schemas["Basis"];

/** The Merchandizable demo shop (prototype only). Outcomes are generated by Python: see mock/demo.ts. */
export type DemoChartRange = { min_cm: number; max_cm: number };
export type DemoChart = {
  title: string;
  disclaimer: string;
  basis: string;
  sizing_mode: string;
  unavailable_modes: string[];
  rows: {
    label: string;
    eu: string;
    uk: string;
    chest: DemoChartRange;
    waist: DemoChartRange;
    hips: DemoChartRange;
  }[];
};
export type CheckView = CheckResult & {
  demo?: {
    shop_name: string;
    sold_sizes: string[];
    chart: DemoChart;
    sample_label: string | null;
  };
};

/** Server-Sent Event payloads (not part of OpenAPI). Mirrors app/pipeline/progress.py. */
export type StepId = "product" | "prices" | "fit" | "seller";
export type ProgressEvent = {
  type: "step" | "complete" | "failed" | "cancelled";
  step?: StepId;
  status?: "active" | "done";
  index?: number;
  total?: number;
  label?: string;
  detail?: string;
  message?: string;
};

/** Post-purchase feedback (backend endpoint arrives in Phase 4). */
export type FitFeedback = "too_tight" | "fits_well" | "too_loose";
export type HeldBackReason = "price" | "fit_concern" | "seller_risk";
export type Feedback =
  | {
      purchased: true;
      option_rank: number;
      fit: FitFeedback;
      fit_dimension: string | null;
    }
  | { purchased: false; option_rank: number; reasons: HeldBackReason[] };

export class ApiError extends Error {
  constructor(
    public status: number,
    message: string,
  ) {
    super(message);
  }
}

/** The server's own message when it sent one; otherwise the caller's fallback. */
export function errorMessage(err: unknown, fallback: string): string {
  return err instanceof ApiError ? err.message : fallback;
}

export interface ApiClient {
  mode: "mock" | "live";
  getProfile(): Promise<Profile | null>;
  saveProfile(profile: ProfileIn): Promise<void>;
  searchBrands(query?: string, limit?: number): Promise<Brand[]>;
  getMeasurements(): Promise<Catalog>;
  createCheck(
    url: string,
    options?: { shopId?: string; sampleId?: string },
  ): Promise<{ id: string }>;
  /** Streams progress for a check; returns an unsubscribe function. */
  subscribe(id: string, onEvent: (event: ProgressEvent) => void): () => void;
  cancelCheck(id: string): Promise<void>;
  getCheck(id: string): Promise<CheckView | null>;
  recentChecks(limit?: number): Promise<CheckSummary[]>;
  getFeedback(id: string): Promise<Feedback | null>;
  submitFeedback(id: string, feedback: Feedback): Promise<void>;
}
